-- Create daily_stats table for 8+8+8 tracking
create table if not exists daily_stats (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  date date not null default CURRENT_DATE,
  user_id uuid references auth.users not null,
  
  sleep_hours numeric(4,2) default 0,
  work_hours numeric(4,2) default 0,
  leisure_hours numeric(4,2) default 0,
  
  unique(user_id, date)
);

-- Enable RLS
alter table daily_stats enable row level security;

-- Policies
create policy "Users can view their own daily stats"
  on daily_stats for select
  using ( auth.uid() = user_id );

create policy "Users can insert their own daily stats"
  on daily_stats for insert
  with check ( auth.uid() = user_id );

create policy "Users can update their own daily stats"
  on daily_stats for update
  using ( auth.uid() = user_id );

create policy "Users can delete their own daily stats"
  on daily_stats for delete
  using ( auth.uid() = user_id );
