-- Consolidated SQL Script for Habits App

-- 1. Create HABITS table
create table if not exists habits (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  title text not null,
  description text,
  user_id uuid references auth.users not null,
  frequency text not null default 'daily',
  streak integer default 0
);

-- 2. Enable RLS on habits
alter table habits enable row level security;

-- 3. Create policies for habits (drop existing ones to avoid errors if re-running)
drop policy if exists "Users can view their own habits" on habits;
create policy "Users can view their own habits" on habits for select using ( auth.uid() = user_id );

drop policy if exists "Users can insert their own habits" on habits;
create policy "Users can insert their own habits" on habits for insert with check ( auth.uid() = user_id );

drop policy if exists "Users can update their own habits" on habits;
create policy "Users can update their own habits" on habits for update using ( auth.uid() = user_id );

drop policy if exists "Users can delete their own habits" on habits;
create policy "Users can delete their own habits" on habits for delete using ( auth.uid() = user_id );


-- 4. Create HABIT_LOGS table
create table if not exists habit_logs (
  id bigint generated by default as identity primary key,
  habit_id bigint references habits(id) on delete cascade not null,
  completed_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 5. Enable RLS on logs
alter table habit_logs enable row level security;

-- 6. Create policies for logs
drop policy if exists "Users can view their own habit logs" on habit_logs;
create policy "Users can view their own habit logs" on habit_logs for select using ( exists ( select 1 from habits where id = habit_logs.habit_id and user_id = auth.uid() ) );

drop policy if exists "Users can insert their own habit logs" on habit_logs;
create policy "Users can insert their own habit logs" on habit_logs for insert with check ( exists ( select 1 from habits where id = habit_logs.habit_id and user_id = auth.uid() ) );

drop policy if exists "Users can delete their own habit logs" on habit_logs;
create policy "Users can delete their own habit logs" on habit_logs for delete using ( exists ( select 1 from habits where id = habit_logs.habit_id and user_id = auth.uid() ) );


-- 7. Helper Functions (RPC)
create or replace function increment_streak(row_id bigint)
returns void as $$
begin
  update habits
  set streak = streak + 1
  where id = row_id;
end;
$$ language plpgsql;

create or replace function decrement_streak(row_id bigint)
returns void as $$
begin
  update habits
  set streak = greatest(0, streak - 1)
  where id = row_id;
end;
$$ language plpgsql;
